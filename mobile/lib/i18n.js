export const dictionaries = { en, ar, ta };
export const LANGUAGES = ['en', 'ar', 'ta'];

function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined || params[k] === null ? '' : String(params[k])));
}

export function translate(lang, key, params) {
  const dict = dictionaries[lang] || en;
  const str = dict[key] ?? en[key] ?? key;
  return interpolate(str, params);
}

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('en');
  const [ready, setReady] = useState(false);

  useEffect(() => {
    storage
      .getItem(LANG_KEY)
      .then((v) => {
        if (v === 'ar' || v === 'en' || v === 'ta') setLangState(v);
      })
      .catch(() => {})
      .finally(() => setReady(true));
  }, []);

  const setLang = useCallback((next) => {
    setLangState(next);
    storage.setItem(LANG_KEY, next).catch(() => {});
  }, []);

  const value = useMemo(() => {
    const isRTL = lang === 'ar';
    // We never force-restart I18nManager. If the native layout direction
    // differs from the chosen language we mirror manually.
    const flip = isRTL !== I18nManager.isRTL;
    return {
      lang,
      ready,
      isRTL,
      setLang,
      // cycles English → العربية → தமிழ்
      toggleLang: () => setLang(LANGUAGES[(LANGUAGES.indexOf(lang) + 1) % LANGUAGES.length]),
      t: (key, params) => translate(lang, key, params),
      // Style helpers for manual RTL
      row: { flexDirection: flip ? 'row-reverse' : 'row' },
      textAlign: { textAlign: flip ? 'right' : 'left', writingDirection: isRTL ? 'rtl' : 'ltr' },
      alignStart: { alignItems: flip ? 'flex-end' : 'flex-start' },
      chevron: isRTL ? 'chevron-back' : 'chevron-forward',
    };
  }, [lang, ready, setLang]);

  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

export const useT = () => useI18n().t;
